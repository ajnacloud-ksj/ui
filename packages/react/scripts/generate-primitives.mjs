import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(new URL("../package.json", import.meta.url));
const excluded = new Set([
  "package.json",
  "types",
  "esm",
  "merge-props",
  "use-render",
]);
const header = "// Generated by pnpm codegen:primitives. Do not edit.\n";

export async function generatePrimitives({ check = false } = {}) {
  const baseUI = require("@base-ui/react/package.json");
  const subpaths = Object.keys(baseUI.exports)
    .filter((key) => /^\.\/[a-z][a-z0-9-]*$/.test(key))
    .map((key) => key.slice(2))
    .filter((name) => !name.startsWith("unstable-") && !excluded.has(name))
    .sort();
  const manifestPath = join(packageRoot, "package.json");
  const originalManifest = await readFile(manifestPath, "utf8");
  const manifest = JSON.parse(originalManifest);
  const primitiveDirectory = join(packageRoot, "src/primitives");
  const files = new Map();

  files.set(
    join(packageRoot, "src/primitives/index.ts"),
    header +
      "\n" +
      subpaths
        .map((name) => `export * from "@base-ui/react/${name}";`)
        .join("\n") +
      "\n",
  );
  manifest.exports = Object.fromEntries(
    Object.entries(manifest.exports).filter(
      ([key]) => key !== "./primitives" && !key.startsWith("./primitives/"),
    ),
  );
  manifest.exports["./primitives"] = {
    types: "./dist/primitives.d.ts",
    import: "./dist/primitives.js",
  };
  for (const name of subpaths) {
    files.set(
      join(primitiveDirectory, `${name}.ts`),
      `${header}\nexport * from "@base-ui/react/${name}";\n`,
    );
    manifest.exports[`./primitives/${name}`] = {
      types: `./dist/primitives/${name}.d.ts`,
      import: `./dist/primitives/${name}.js`,
    };
  }
  files.set(manifestPath, JSON.stringify(manifest, null, 2) + "\n");

  let existing = [];
  try {
    existing = await readdir(primitiveDirectory);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  const stale = [];
  for (const name of existing.filter((name) => name.endsWith(".ts"))) {
    const path = join(primitiveDirectory, name);
    if (!files.has(path) && (await readFile(path, "utf8")).startsWith(header))
      stale.push(path);
  }
  const changed = [];
  for (const [path, expected] of files) {
    let actual;
    try {
      actual = await readFile(path, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (actual !== expected) changed.push(path);
  }

  if (check) {
    if (changed.length || stale.length)
      throw new Error(
        "Primitive exports are out of date. Run pnpm codegen:primitives.",
      );
    console.log(
      `Primitive exports match Base UI ${baseUI.version} (${subpaths.length} entry points).`,
    );
    return;
  }
  await mkdir(primitiveDirectory, { recursive: true });
  for (const path of stale) await rm(path);
  for (const path of changed) await writeFile(path, files.get(path));
  console.log(
    `Generated ${subpaths.length} primitive entry points from Base UI ${baseUI.version}.`,
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url)
  await generatePrimitives({ check: process.argv.includes("--check") });
